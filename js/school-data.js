/**
 * Get all schools as a flat array
 */
export const getAllSchools = () => {
    const all = [];
    for (const region in SCHOOLS_BY_REGION) {
        const regionData = SCHOOLS_BY_REGION[region];
        if (regionData.public) {
            regionData.public.forEach(school => {
                all.push({ ...school, region, category: 'public' });
            });
        }
        if (regionData.private) {
            regionData.private.forEach(school => {
                all.push({ ...school, region, category: 'private' });
            });
        }
    }
    return all;
};

/**
 * Get schools by region
 */
export const getSchoolsByRegion = (region) => {
    return SCHOOLS_BY_REGION[region] || { public: [], private: [] };
};

/**
 * Get schools by program
 */
export const getSchoolsByProgram = (program) => {
    const all = getAllSchools();
    return all.filter(school => school.programs.includes(program));
};

/**
 * Get unique regions
 */
export const getRegions = () => {
    return Object.keys(SCHOOLS_BY_REGION);
};

/**
 * Get unique programs across all schools
 */
export const getAllPrograms = () => {
    const all = getAllSchools();
    const programs = new Set();
    all.forEach(school => {
        school.programs.forEach(p => programs.add(p));
    });
    return Array.from(programs).sort();
};

/**
 * Get school categories (A, B, C)
 */
export const getSchoolCategory = (school) => {
    return 'C';
};

// Export default
export default {
    SCHOOLS_BY_REGION,
    getAllSchools,
    getSchoolsByRegion,
    getSchoolsByProgram,
    getRegions,
    getAllPrograms,
    getSchoolCategory
};